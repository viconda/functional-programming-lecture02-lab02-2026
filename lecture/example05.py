"""Пример 5. Условное выражение."""

from __future__ import annotations


def sign(x: float) -> str:
    """Вернуть название знака конечного действительного числа."""
    return "положительное" if x > 0 else ("отрицательное" if x < 0 else "ноль")


def main() -> None:
    """Проверить все три ветви условного выражения."""
    print("Пример 5. Условное выражение")
    result = [sign(v) for v in (5, -2, 0)]
    print(result)
    assert result == ["положительное", "отрицательное", "ноль"]
    assert sign(0.25) == "положительное" and sign(-0.25) == "отрицательное"
    assert sign(-0.0) == "ноль"
    print("Проверки: положительное, отрицательное, ноль и дроби — OK")


if __name__ == "__main__":
    main()
